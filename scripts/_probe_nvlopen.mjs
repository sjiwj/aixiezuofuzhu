const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR'; return r.result && r.result.result && r.result.result.value }
console.log('__nvlOpen exists =', await ev('typeof window.__nvlOpen'))
console.log('open writing =', JSON.stringify(await ev('window.__nvlOpen ? window.__nvlOpen("novel-writing") : "no-fn"')))
console.log('open settings =', JSON.stringify(await ev('window.__nvlOpen ? window.__nvlOpen("novel-settings") : "no-fn"')))
console.log('dataset =', JSON.stringify(await ev('String(document.body.dataset.activePanel||"")')))
console.log('textarea now =', await ev('document.querySelectorAll(".nvl-textarea").length'))
ws.close(); process.exit(0)
