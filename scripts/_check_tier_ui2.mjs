const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,150); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))

await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim().startsWith("项目")); if(b) b.click(); return "ok" })()')
await wait(1500)
console.log('1 click chapter =', await ev('(() => { const row=[...document.querySelectorAll(".nvl-tree__chapter")].find(r=>(r.textContent||"").includes("柴没砍完")); if(!row) return "miss"; row.click(); return "ok" })()'))
await wait(1500)
console.log('2 click AI write =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim()==="AI 写这一章"); if(!b) return "miss"; if(b.disabled) return "disabled"; b.click(); return "ok" })()'))
await wait(2500)
console.log('3 gate options =', JSON.stringify(await ev('([...document.querySelectorAll(".nvl-decide button")].map(b=>(b.textContent||"").trim()))')))
console.log('4 click replace =', await ev('(() => { const b=[...document.querySelectorAll(".nvl-decide button")].find(x=>(x.textContent||"").includes("覆盖")); if(!b) return "miss"; b.click(); return "ok" })()'))
await wait(60000)
const tn = await ev('(() => { const els=[...document.querySelectorAll(".nvl-dim")]; const hit=els.map(e=>(e.textContent||"").trim()).filter(t=>t.includes("重点章")||t.includes("卷末")||t.includes("deepseek")); return hit.slice(0,3) })()')
console.log('5 tierNote =', JSON.stringify(tn))
const body = String(await ev('(document.body.innerText||"").replace(/\\s+/g," ")'))
