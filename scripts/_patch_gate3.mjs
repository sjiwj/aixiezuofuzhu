
import fs from 'node:fs'
const p = 'D:/NovelApp/scripts/l3_l4_check.py'
let s = fs.readFileSync(p, 'utf8')
if (s.includes('def check_gate3')) { console.log('ALREADY'); process.exit(0) }
const eol = s.includes('\r\n') ? '\r\n' : '\n'

const anchor = 'def resolve_path(p, default_rel):'
if (!s.includes(anchor)) throw new Error('resolve_path anchor')

const fns = [
'# ---------------------------------------------------------------- 闸 3 三维（物品 / 能力 / 伏笔）',
'def _book_dir_of(chapter_path):',
'    """章节文件所在书的根目录：<书>/章节/x.md -> <书>"""',
'    d = os.path.dirname(os.path.abspath(chapter_path))',
'    return os.path.dirname(d) if os.path.basename(d) == "章节" else d',
'',
'',
'def _read_text(path):',
'    try:',
'        with open(path, encoding="utf-8-sig") as f:',
'            return f.read()',
'    except OSError:',
'        return ""',
'',
'',
'def _table_rows(text):',
'    """markdown 表格 -> 表头映射的行字典列表（跳过 --- 分隔行）。"""',
'    rows, head = [], None',
'    for ln in text.split("\\n"):',
'        st = ln.strip()',
'        if not st.startswith("|"):',
'            continue',
'        cells = [c.strip() for c in st.strip("|").split("|")]',
'        if all(set(c) <= set("-: ") for c in cells if c):',
'            continue',
'        if head is None:',
'            head = cells',
'            continue',
'        rows.append({head[i]: cells[i] for i in range(min(len(head), len(cells)))})',
'    return rows',
'',
'',
'def check_items(text, book_dir):',
'    """物品一致性：状态表记在身上的东西，正文说丢了/没了/留在某处 -> 要人工确认。"""',
'    st = _read_text(os.path.join(book_dir, "设定库", "角色状态.md"))',
'    if not st:',
'        return [], {"items_checked": 0}',
'    items = set()',
'    for ln in st.split("\\n"):',
'        if "身上物品" not in ln:',
'            continue',
'        val = ln.split("：", 1)[-1] if "：" in ln else ln.split(":", 1)[-1]',
'        for tok in re.split(r"[、，,；;（）()]", val):',
'            tok = tok.strip().strip("*").strip()',
'            if 2 <= len(tok) <= 10 and not re.search(r"[0-9A-Za-z]", tok):',
'                items.add(tok)',
'    if not items:',
'        return [], {"items_checked": 0}',
'    lost = re.compile(r"(丢了|没了|不见了|找不到|只剩|落在|留在|忘在)")',
'    issues = []',
'    seen = set()',
'    for line_no, para in iter_paragraphs(text):',
'        m = lost.search(para)',
'        if not m:',
'            continue',
'        for it in items:',
'            if it in para and it not in seen:',
'                seen.add(it)',
'                issues.append({"rule": "item_vs_state", "severity": "warn", "line": line_no,',
'                               "message": "「%s」与状态表可能不一致：正文出现「%s」" % (it, m.group(1)),',
'                               "snippet": para[:80]})',
'    return issues, {"items_checked": len(items)}',
'',
'',
'def check_power(text, book_dir):',
'    """能力/境界：正文出现的境界词必须在 力量体系.md 的清单里。"""',
'    pw = _read_text(os.path.join(book_dir, "设定库", "力量体系.md"))',
'    if not pw:',
'        return [], {"realms": 0}',
'    known, order = [], []',
'    for r in _table_rows(pw):',
'        name = (r.get("境界") or "").strip()',
'        if name and not name.startswith("（"):',
'            known.append(name)',
'            order.append(name)',
'    if not known:',
'        return [], {"realms": 0}',
'    issues = []',
'    pat = re.compile(r"(练气[一二三四五六七八九十]+层|筑基[一二三四五六七八九十]*|金丹|元婴|化神|渡劫)")',
'    seen = set()',
'    for m in pat.finditer(text):',
'        w = m.group(1)',
'        if w in seen:',
'            continue',
'        if w not in known:',
'            seen.add(w)',
'            issues.append({"rule": "realm_unknown", "severity": "info", "line": _line_of(text, m.start()),',
'                           "message": "境界「%s」不在 力量体系.md 里（已有：%s）" % (w, "、".join(known[:8]))})',
'    return issues, {"realms": len(known), "realm_words": len(seen)}',
'',
'',
'def check_foreshadow(text, chapter_path):',
'    """伏笔：本章触及哪些、哪些埋太久没动。"""',
'    book_dir = _book_dir_of(chapter_path)',
'    fv = _read_text(os.path.join(book_dir, "设定库", "伏笔.md"))',
'    if not fv:',
'        return [], {"foreshadow": 0}',
'    rows = [r for r in _table_rows(fv) if r.get("编号")]',
'    if not rows:',
'        return [], {"foreshadow": 0}',
'    m = re.search(r"(\\d{1,4})", os.path.basename(chapter_path))',
'    ch_no = int(m.group(1)) if m else 0',
'    touched, stale = [], []',
'    for r in rows:',
'        status = str(r.get("状态") or "").strip()',
'        if status and status not in ("悬着", "未收"):',
'            continue',
'        content = str(r.get("内容") or "")',
'        keys = [w for w in re.findall(r"[\\u4e00-\\u9fa5]{2,4}", content)][:8]',
'        hit = [w for w in keys if w in text]',
'        pid = str(r.get("编号"))',
'        if hit:',
'            touched.append(pid)',
'            continue',
'        buried_m = re.search(r"(\\d{1,4})", str(r.get("埋在哪章") or ""))',
'        buried = int(buried_m.group(1)) if buried_m else 0',
'        if buried and ch_no and (ch_no - buried) >= 5:',
'            stale.append((pid, buried))',
'    issues = []',
'    if touched:',
'        issues.append({"rule": "foreshadow_touched", "severity": "info",',
'                       "message": "本章触及伏笔：%s" % "、".join(touched)})',
'    for pid, buried in stale:',
'        issues.append({"rule": "foreshadow_stale", "severity": "warn",',
'                       "message": "伏笔 %s 埋在第 %d 章，已 %d 章没动" % (pid, buried, ch_no - buried)})',
'    return issues, {"foreshadow": len(rows), "foreshadow_touched": len(touched),',
'                    "foreshadow_stale": len(stale)}',
'',
'',
'def check_gate3(text, chapter_path):',
'    """闸 3 三维统一入口：物品 / 能力 / 伏笔。数据来自本书 设定库/。"""',
'    book_dir = _book_dir_of(chapter_path)',
'    i1, s1 = check_items(text, book_dir)',
'    i2, s2 = check_power(text, book_dir)',
'    i3, s3 = check_foreshadow(text, chapter_path)',
'    stats = {}',
'    stats.update(s1)',
'    stats.update(s2)',
'    stats.update(s3)',
'    return i1 + i2 + i3, stats',
'',
'',
].join(eol)

s = s.replace(anchor, fns + anchor)

// main 接线
const mainOld = [
  '    l4_issues, days_found = check_speed(text, unit, rules.get("l4", {}))'.replace(/"/g, "'"),
  '    season_issues, season_stats = check_season(text, rules.get("season", {}))'.replace(/"/g, "'"),
  '    all_issues = l3_issues + l4_issues + season_issues',
].join(eol)
if (!s.includes(mainOld)) throw new Error('main anchor')
const mainNew = [
  "    l4_issues, days_found = check_speed(text, unit, rules.get('l4', {}))",
  "    season_issues, season_stats = check_season(text, rules.get('season', {}))",
  "    g3_issues, g3_stats = check_gate3(text, path)",
  "    all_issues = l3_issues + l4_issues + season_issues + g3_issues",
].join(eol)
s = s.split(mainOld).join(mainNew)

// stats 合并
const stOld = "            'l4': {'time_distance_mentions': days_found, **season_stats},"
if (!s.includes(stOld)) throw new Error('stats anchor')
s = s.replace(stOld, [
  "            'l4': {'time_distance_mentions': days_found, **season_stats},",
  "            'gate3': g3_stats,",
].join(eol))

fs.writeFileSync(p, s, 'utf8')
console.log('l3_l4: +check_gate3 (items/power/foreshadow)')
