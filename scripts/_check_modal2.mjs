const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,200); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))

console.log('openSettings =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim().startsWith("设置")); if(!b) return "no-btn"; b.click(); return "ok" })()'))
await wait(1400)
console.log('rows =', JSON.stringify(await ev('([...document.querySelectorAll(".nvl-setrow")].map(r=>(r.textContent||"").trim().slice(0,26)))')))
console.log('clickView =', await ev('(() => { const row=[...document.querySelectorAll(".nvl-setrow")].find(r=>(r.textContent||"").includes("关于与许可")); if(!row) return "no-row"; const b=row.querySelector("button"); if(!b) return "no-btn"; b.click(); return "ok:" + b.textContent.trim() })()'))
await wait(900)
console.log('modals =', await ev('document.querySelectorAll(".nvl-modal").length'))
console.log('modalText =', JSON.stringify(String(await ev('(() => { const m=[...document.querySelectorAll(".nvl-modal")].pop(); return m ? (m.textContent||"").replace(/\\s+/g," ").slice(0,400) : "none" })()'))))
ws.close(); process.exit(0)
