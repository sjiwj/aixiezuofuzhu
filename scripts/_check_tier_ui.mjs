const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,150); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))

await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim().startsWith("码字")); if(b) b.click(); return "ok" })()')
await wait(1500)
console.log('chapter =', JSON.stringify(await ev('(document.querySelector(".nvl-editor__title")||{}).textContent || ""')))
console.log('buttons =', JSON.stringify(await ev('([...document.querySelectorAll("button")].map(b=>(b.textContent||"").trim()).filter(t=>t && (t.includes("AI")||t.includes("写")||t.includes("润"))).slice(0,8))')))
console.log('click AI =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>/AI\s*写作|开始写|让 AI 写/.test(x.textContent||"")); if(!b) return "miss"; b.click(); return "ok" })()'))
await wait(2000)
console.log('after click text =', JSON.stringify(String(await ev('(document.body.innerText||"").replace(/\\s+/g," ").slice(0,300)'))))
ws.close(); process.exit(0)
