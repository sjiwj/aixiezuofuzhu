const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR'; return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
console.log('1 open writing =', JSON.stringify(await ev('window.__nvlOpen("novel-writing")')))
await wait(800)
console.log('2 textarea =', await ev('document.querySelectorAll(".nvl-textarea").length'))
console.log('3 dataset =', JSON.stringify(await ev('String(document.body.dataset.activePanel||"")')))
await ev('(function(){var b=[].slice.call(document.querySelectorAll("button")).filter(function(x){return (x.textContent||"").trim().indexOf("项目")===0})[0];if(b)b.click();return "ok"})()')
await wait(1200)
console.log('4 back to projects, panel =', JSON.stringify(await ev('String(document.body.dataset.activePanel||"")')))
console.log('5 click AI write =', JSON.stringify(await ev('(function(){var b=[].slice.call(document.querySelectorAll("button")).filter(function(x){return (x.textContent||"").trim()==="AI 写这一章"})[0];if(!b)return "miss";b.click();return "clicked"})()')))
await wait(6000)
console.log('6 panel after =', JSON.stringify(await ev('String(document.body.dataset.activePanel||"")')))
console.log('7 textarea =', await ev('document.querySelectorAll(".nvl-textarea").length'))
const t = String(await ev('(document.body.innerText||"").replace(/\s+/g," ")'))
const marks = ['AI 正在写', '写作中', '花费 ¥', '已写完', '资料不全', '先选一章'].filter(function (m) { return t.indexOf(m) >= 0 })
console.log('8 marks =', JSON.stringify(marks))
console.log('9 head =', JSON.stringify(t.slice(0, 160)))
ws.close(); process.exit(0)
