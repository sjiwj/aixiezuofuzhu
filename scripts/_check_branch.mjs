const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,200); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const clickBtn = (n) => ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim().startsWith(' + JSON.stringify(n) + ')); if(!b) return "miss"; b.click(); return "ok" })()')
const clickBook = (n) => ev('(() => { const el=[...document.querySelectorAll(".nvl-tree__bookname")].find(e=>(e.textContent||"").trim().replace(/^[v>]\\s*/,"").startsWith(' + JSON.stringify(n) + ')); if(!el) return "miss"; el.click(); return "ok" })()')

console.log('项目 =', await clickBtn('项目')); await wait(800)
console.log('点<书名> =', await clickBook('<书名>')); await wait(1600)
console.log('设定库 =', await clickBtn('设定库')); await wait(1200)
console.log('LIB =', JSON.stringify(String(await ev('(document.body.innerText||"").replace(/\\s+/g," ").slice(0,420)'))))

// 新建分支
console.log('点+分支 =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim()==="+ 分支"); if(!b) return "miss"; b.click(); return "ok" })()'))
await wait(600)
console.log('输入分支名 =', await ev('(() => { const d=document.querySelector("[role=dialog]"); if(!d) return "no-dialog"; const i=d.querySelector("input"); i.value="角色卡"; i.dispatchEvent(new Event("input",{bubbles:true})); const ok=[...d.querySelectorAll("button")].find(b=>(b.textContent||"").trim()==="确定"); ok.click(); return "ok" })()'))
await wait(1500)
console.log('AFTER-BRANCH =', JSON.stringify(String(await ev('(document.body.innerText||"").replace(/\\s+/g," ").slice(0,420)'))))
ws.close(); process.exit(0)
