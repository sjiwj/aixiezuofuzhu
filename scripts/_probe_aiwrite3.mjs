const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,200); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const panel = async () => String(await ev('(function(){var e=document.querySelector("[data-active-panel]");return e?e.getAttribute("data-active-panel"):"none"})()'))
await ev('(function(){window.__t=[];window.addEventListener("novelapp:ai-write",function(e){window.__t.push("ai-write")});window.addEventListener("novelapp:chapter",function(e){window.__t.push("chapter")});return "ok"})()')
console.log('panel before =', await panel())
console.log('click =', await ev('(function(){var b=[].slice.call(document.querySelectorAll("button")).filter(function(x){return (x.textContent||"").trim()==="AI 写这一章"})[0];if(!b)return "miss";b.click();return "clicked"})()'))
await wait(2000)
console.log('panel after =', await panel())
console.log('events =', JSON.stringify(await ev('window.__t')))
console.log('textarea =', await ev('document.querySelectorAll(".nvl-textarea").length'))
console.log('writeGate =', JSON.stringify(await ev('(function(){var d=document.querySelector(".nvl-decide");return d?(d.textContent||"").trim().slice(0,120):null})()')))
ws.close(); process.exit(0)
