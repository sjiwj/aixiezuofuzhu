const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,200); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const txt = async () => String(await ev('(document.body.innerText||"").replace(/\\s+/g," ")'))

console.log('1 开始审稿 =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim()==="开始审稿"); if(!b) return "miss"; if(b.disabled) return "disabled"; b.click(); return "ok" })()'))
await wait(46000)
const t1 = await txt()
console.log('2 hasReviseBtn =', t1.includes("按意见改"), '| done =', /看它的理由/.test(t1))
console.log('2 点按意见改 =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim()==="按意见改"); if(!b) return "miss"; b.click(); return "ok" })()'))
await wait(90000)
const t2 = await txt()
console.log('3 hasRevised =', t2.includes("改后正文"), '| hasAdopt =', t2.includes("采用并复检"))
console.log('3 采用 =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim()==="采用并复检"); if(!b) return "miss"; b.click(); return "ok" })()'))
await wait(60000)
const t3 = await txt()
console.log('4 hasRecheck =', t3.includes("复检"), '| 复检片段 =', JSON.stringify(t3.slice(t3.indexOf("复检"), t3.indexOf("复检") + 120)))
ws.close(); process.exit(0)
