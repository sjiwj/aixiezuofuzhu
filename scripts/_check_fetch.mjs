const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,300); return r.result && r.result.result && r.result.result.value }
console.log('origin =', JSON.stringify(await ev('location.origin')))
console.log('href =', JSON.stringify(await ev('location.href.slice(0,80)')))
console.log('handshake =', await ev('fetch("http://127.0.0.1:18760/novelapp/handshake").then(r => r.status + ":" + (r.headers.get("access-control-allow-origin")||"no-cors")).catch(e => "ERR:" + e.message)'))
console.log('projects =', await ev('fetch("http://127.0.0.1:18760/novelapp/projects").then(r => r.status).catch(e => "ERR:" + e.message)'))
console.log('api health =', await ev('fetch("http://127.0.0.1:18760/api/health").then(r => r.status).catch(e => "ERR:" + e.message)'))
ws.close(); process.exit(0)
