const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:'+JSON.stringify(r.result.exceptionDetails.exception&&r.result.exceptionDetails.exception.description||'').slice(0,300); return r.result && r.result.result && r.result.result.value }
console.log('body text tail:', JSON.stringify(String(await ev('document.body.innerText.slice(-300)'))))
console.log('nvl panels:', await ev('document.querySelectorAll(".nvl-pane,.nvl-main,[class*=nvl-]").length'))
console.log('loading text present:', await ev('document.body.innerText.includes("正在加载创作工具")'))
console.log('errors:', JSON.stringify(await ev('(function(){return (window.__errs||[]).slice(-5)})()')))
ws.close(); process.exit(0)
