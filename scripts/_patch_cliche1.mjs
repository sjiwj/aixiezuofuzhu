
import fs from 'node:fs'
const p = 'D:/NovelApp/scripts/l1_l2_check.py'
let s = fs.readFileSync(p, 'utf8')
if (s.includes('def check_cliche')) { console.log('ALREADY'); process.exit(0) }
const eol = s.includes('\r\n') ? '\r\n' : '\n'

// 1) load_cfg 末尾挂上 cliche
const cfgAnchor = "    for section in ('l1', 'l2'):" + eol + "        val = data.get(section)" + eol + "        if isinstance(val, dict):" + eol + "            cfg[section].update(val)" + eol + "    return cfg"
