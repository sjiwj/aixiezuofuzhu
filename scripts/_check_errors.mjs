const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
const logs = []
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.method === 'Runtime.consoleAPICalled') { logs.push('[' + m.params.type + '] ' + (m.params.args||[]).map(a=>a.value||a.description||'').join(' ').slice(0,200)) } if (m.method === 'Runtime.exceptionThrown') { logs.push('[EX] ' + JSON.stringify(m.params.exceptionDetails).slice(0,300)) } if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,250); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
await ev('(function(){var bs=[].slice.call(document.querySelectorAll("button"));var b=bs.filter(function(x){return (x.textContent||"").trim()==="\u7801\u5b57"})[0];if(b)b.click();return "ok"})()')
await wait(2500)
console.log('=== console ===')
console.log(logs.slice(-14).join("\n") || "(none)")
console.log('=== panel state ===')
console.log('activePanel attr =', await ev('document.querySelector("[data-active-panel]") ? document.querySelector("[data-active-panel]").getAttribute("data-active-panel") : "none"'))
console.log('nvl-pane count =', await ev('document.querySelectorAll(".nvl-pane").length'))
console.log('body text head =', JSON.stringify(String(await ev('(document.body.innerText||"").replace(/\s+/g," ").slice(0,180)'))))
ws.close(); process.exit(0)
