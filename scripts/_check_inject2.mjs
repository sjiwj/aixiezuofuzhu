const list = await (await fetch('http://127.0.0.1:9650/json/list')).json()
const page = list.find((t) => t.type === 'page')
const ws = new WebSocket(page.webSocketDebuggerUrl)
let id = 0; const pending = new Map()
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id) } })
await new Promise((r) => ws.addEventListener('open', r))
const call = (method, params) => new Promise((r) => { const i = ++id; pending.set(i, r); ws.send(JSON.stringify({ id: i, method, params: params || {} })) })
await call('Runtime.enable')
const ev = async (x) => { const r = await call('Runtime.evaluate', { expression: x, returnByValue: true, awaitPromise: true }); if (r.result && r.result.exceptionDetails) return 'ERR:' + JSON.stringify(r.result.exceptionDetails).slice(0,200); return r.result && r.result.result && r.result.result.value }
const wait = (ms) => new Promise((r) => setTimeout(r, ms))
const click = (n) => ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim().startsWith(' + JSON.stringify(n) + ')); if(!b) return "miss"; b.click(); return "ok" })()')

// 先切到<书名>第一章：项目 → 点书 → 点章节 → 审稿
await click('项目'); await wait(900)
await ev('(() => { const el=[...document.querySelectorAll(".nvl-tree__bookname")].find(e=>(e.textContent||"").trim().replace(/^[v>]\\s*/,"").startsWith("<书名>")); if(el) el.click(); return "ok" })()')
await wait(1500)
await ev('(() => { const row=[...document.querySelectorAll(".nvl-tree__chapter")].find(r=>(r.textContent||"").includes("柴没砍完")); if(!row) return "no-row"; row.click(); return "ok" })()')
await wait(1200)
await click('审稿'); await wait(1500)
console.log('path =', JSON.stringify(await ev('(document.querySelector(".nvl-review__path")||{}).value')))
console.log('gate =', JSON.stringify(String(await ev('(document.body.innerText||"").replace(/\\s+/g," ").slice(60,200)'))))
console.log('start =', await ev('(() => { const b=[...document.querySelectorAll("button")].find(x=>(x.textContent||"").trim()==="开始审稿"); if(!b) return "miss"; if(b.disabled) return "disabled"; b.click(); return "ok" })()'))
await wait(34000)
const fin = String(await ev('(document.body.innerText||"").replace(/\\s+/g," ")'))
console.log('DONE =', JSON.stringify(fin.slice(60, 460)))
console.log('hasInjected =', fin.includes('本次带上的资料'))
ws.close(); process.exit(0)
